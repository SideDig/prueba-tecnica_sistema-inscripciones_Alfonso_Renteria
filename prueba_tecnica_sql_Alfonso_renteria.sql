 FROM historial_estatus h
 INNER JOIN inscripciones i ON h.id_inscripcion = i.id_inscripcion
 INNER JOIN alumnos a ON i.id_alumno = a.id_alumno
 INNER JOIN programas p ON i.id_programa = p.id_programa
 WHERE a.id_alumno = 1007
 ORDER BY h.fecha_cambio ASC;
 
-- ============================================================
-- Alumnos que pasaron de baja_empresa a activo (reingreso)
-- ==========================================================
 SELECT
    a.id_alumno,
    a.nombre AS alumno,
    p.nombre_programa AS programa,
    h.fecha_cambio AS fecha_reingreso,
    h.motivo
 FROM historial_estatus h
 INNER JOIN inscripciones i ON h.id_inscripcion = i.id_inscripcion
 INNER JOIN alumnos a ON i.id_alumno = a.id_alumno
 INNER JOIN programas p ON i.id_programa = p.id_programa
 WHERE h.estatus_anterior = 'baja_empresa'
 AND h.estatus_nuevo IN ('activo', 'reingreso')
 ORDER BY h.fecha_cambio DESC;
 
 -- ============================================================
-- INDICADOR 
-- ============================================================
-- ================================================================================================
-- Nombre del indicador: Tasa de Retencion Activa por Programa (TRAP)
-- 
-- Definición y Fórmula:
--   TRAP es igual a utilizar esta formula (Alumnos que estan Activos + Alumnos que estan inscritos + Alumnos ya Egresados) / Total de inscritos * 100
--   este indicador nos ayuda a medir el porcentaje de alumnos que se mantienen en un estado productivo dentro de cada programa academico.
--
-- Justificación:
--   Para mi es importante este indicador para la toma de decisiones porque permite identificar que programas
--   tienen problemas de abandono de programas es decir un TRAP bajo y cuáles retienen mejor a sus alumnos osea TRAP alto,
--   un TRAP bajo puede alertar sobre problemas en la calidad de las clases,
--   convenios de empresas, o la necesidad de actualizar el plan de estudios.
-- ===========================================================================================

SELECT
    p.nombre_programa,
    p.nivel,
    COUNT(*) AS total_inscritos,
    SUM(CASE WHEN i.estatus IN ('activo', 'inscrito', 'egresado') THEN 1 ELSE 0 END) AS alumnos_retenidos,
    SUM(CASE WHEN i.estatus IN ('baja_empresa', 'baja_programa') THEN 1 ELSE 0 END) AS alumnos_perdidos,
    ROUND( SUM(CASE WHEN i.estatus IN ('activo', 'inscrito', 'egresado') THEN 1 ELSE 0 END) / COUNT(*) * 100, 2) AS tasa_retencion_pct
FROM inscripciones i
INNER JOIN programas p ON i.id_programa = p.id_programa
GROUP BY p.id_programa, p.nombre_programa, p.nivel
ORDER BY tasa_retencion_pct DESC;
 

