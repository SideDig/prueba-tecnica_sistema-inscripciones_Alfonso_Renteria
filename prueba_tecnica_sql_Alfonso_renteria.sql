-- stored procedure para registrar cambio de estatus 
-- ============================================================

-- ==========================================================================
-- Stored Procedure: registrar_cambio_estatus
--
-- Descripcion:
--   Registra un cambio de estatus para una inscripcion existente
--   Se conectan 3 tablas que son las de inscripciones, alumnos e historial_estatus.
--
-- Parametros:
--   p_id_inscripcion: Este es el ID de la inscripción que vamos actualizar
--   p_nuevo_estatus: Este sera el nuevo estatus del alumno ya sea uno de estos ('activo', 'suspendido', 'baja_empresa', etc.)
--   p_motivo: Este la razon del cambio y se guardara en historial_estatus)

-- prueba 1: Caso exitoso
--  si se cambia la inscripción 12 de suspendido a activo
--  ejemplo: CALL registrar_cambio_estatus(12, 'activo', 'Alumno liquido su deuda completa');
--  Resultado: "Éxito: Se actualizó el estatus de José Gutiérrez de [suspendido] a [activo]."

-- prueba 2: Caso exitoso
--  Si se cambia la inscripción 16 de suspendido a baja_programa
--  ejemplo: CALL registrar_cambio_estatus(16, 'baja_programa', 'Alumno solicito baja voluntaria');
--  Resultado: "Éxito: Se actualizó el estatus de ..."

-- prueba 3: Error controlado - inscripcion no existe
--  ejemplo: CALL registrar_cambio_estatus(9999, 'activo', 'Prueba de error');
--  Resultado:"La inscripción especificada no existe."

-- prueba 4: Error controlado - mismo estatus
--  CALL registrar_cambio_estatus(1, 'activo', 'Prueba mismo estatus');
--  Resultado:"El alumno ya tiene asignado ese estatus."

--  Este se usa para poder confiramar que ese cambio si se hizo en el historial 
--  SELECT * FROM historial_estatus ORDER BY id_historial DESC LIMIT 3;
-- ==========================================================================

 DROP PROCEDURE IF EXISTS registrar_cambio_estatus;
 DELIMITER //
 CREATE PROCEDURE registrar_cambio_estatus(
   IN p_id_inscripcion INT,
   IN p_nuevo_estatus VARCHAR(20),
   IN p_motivo VARCHAR(255) )
 BEGIN
   DECLARE v_estatus_actual VARCHAR(20) DEFAULT NULL;
   DECLARE v_id_alumno INT DEFAULT NULL;
   DECLARE v_nombre_alumno VARCHAR(150) DEFAULT NULL;
 SELECT i.estatus, i.id_alumno, a.nombre
   INTO v_estatus_actual, v_id_alumno, v_nombre_alumno
   FROM inscripciones i
   INNER JOIN alumnos a ON i.id_alumno = a.id_alumno
   WHERE i.id_inscripcion = p_id_inscripcion;
    IF v_id_alumno IS NULL 
	   THEN 
		 SIGNAL SQLSTATE '45000'
       SET MESSAGE_TEXT = 'Error: La inscripción especificada no existe.';
      ELSEIF v_estatus_actual = p_nuevo_estatus 
		THEN
         SIGNAL SQLSTATE '45000'
         SET MESSAGE_TEXT = 'Error: El alumno ya tiene asignado ese estatus.';
    ELSE
      UPDATE inscripciones
         SET estatus = p_nuevo_estatus
      WHERE id_inscripcion = p_id_inscripcion;
      INSERT INTO historial_estatus (id_inscripcion, estatus_anterior, estatus_nuevo, fecha_cambio, motivo)
       VALUES (p_id_inscripcion, v_estatus_actual, p_nuevo_estatus, CURDATE(), p_motivo);
      SELECT CONCAT('Éxito: Se actualizó el estatus de ', v_nombre_alumno, ' de [', v_estatus_actual, '] a [', p_nuevo_estatus, '].') AS resultado;
    END IF;
 END //

DELIMITER ;
 