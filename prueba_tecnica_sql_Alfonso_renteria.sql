 SELECT DISTINCT
 	 a.id_alumno,
    a.nombre AS alumno,
    p.nombre_programa AS programa,
    h.estatus_anterior,
    h.estatus_nuevo,
    h.fecha_cambio,
    h.motivo
 FROM historial_estatus h
  INNER JOIN inscripciones i ON h.id_inscripcion = i.id_inscripcion
  INNER JOIN alumnos a ON i.id_alumno = a.id_alumno
  INNER JOIN programas p ON i.id_programa = p.id_programa
 WHERE h.fecha_cambio >= CURDATE() - INTERVAL 30 DAY
 AND h.estatus_anterior IS NOT NULL
 ORDER BY h.fecha_cambio DESC;


-- ============================================================
-- Tasa de baja por programa (bajas / total inscritos)
-- ===========================================================

 SELECT p.nombre_programa, COUNT(*) AS total_inscritos,
   SUM(CASE WHEN i.estatus IN ('baja_empresa','baja_programa') 
      THEN 1 ELSE 0 END) AS total_bajas,
   ROUND(SUM(CASE WHEN i.estatus IN ('baja_empresa','baja_programa') 
      THEN 1 ELSE 0 END) / COUNT(*) * 100, 2) AS tasa_baja_programa
  FROM inscripciones i
  INNER JOIN programas p ON i.id_programa = p.id_programa
 GROUP BY p.id_programa, p.nombre_programa
 ORDER BY tasa_baja_programa DESC;

