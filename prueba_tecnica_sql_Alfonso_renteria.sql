CREATE DATABASE IF NOT EXISTS sistema_inscripciones
 CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;

USE sistema_inscripciones;
SET FOREIGN_KEY_CHECKS = 0;
-- ============================================================
-- Limpieza previa de las tablas de manera inversa es decir primero 
-- las que dependen de otras tablas, para evitar errores con las llaves foraneas
-- ============================================================
DROP TABLE IF EXISTS historial_estatus;
DROP TABLE IF EXISTS inscripciones;
DROP TABLE IF EXISTS alumnos;
DROP TABLE IF EXISTS programas;
DROP TABLE IF EXISTS empresas;

-- ============================================================
-- DDL -- CREACION DE TABLAS
-- ============================================================

-- Tabla 1: empresas
-- Todas las empresas sin dependencias de FK
CREATE TABLE empresas (
    id_empresa INT AUTO_INCREMENT PRIMARY KEY,
    nombre_empresa VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Tabla 2: programas
-- todos los programas academicos sin dependencias de FK
CREATE TABLE programas (
    id_programa INT AUTO_INCREMENT PRIMARY KEY,
    nombre_programa VARCHAR(100) NOT NULL,
    nivel ENUM('Bachillerato','Licenciatura','Maestria','Secundaria') NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Tabla 3: alumnos
-- Datos personales del alumno esta depende de empresas (si tiene FK)
CREATE TABLE alumnos (
    id_alumno INT PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    id_empresa INT NOT NULL,
    fecha_ingreso DATE NOT NULL,
    CONSTRAINT fk_alumno_empresa
      FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Tabla 4: inscripciones
-- Relacion alumno-programa con su estatus actual
-- Se incluyen los 7 estatus reales del CSV para mantener integridad
-- como nota el estatus 'reingreso' es semanticamente un estado transitorio hacia 'activo'.
CREATE TABLE inscripciones (
    id_inscripcion INT AUTO_INCREMENT PRIMARY KEY,
    id_alumno INT NOT NULL,
    id_programa INT NOT NULL,
    estatus ENUM('activo','baja_empresa','baja_programa','egresado','inscrito','reingreso','suspendido') NOT NULL,
    fecha_inscripcion DATE NOT NULL,
    CONSTRAINT fk_inscripcion_alumno
        FOREIGN KEY (id_alumno) REFERENCES alumnos(id_alumno),
    CONSTRAINT fk_inscripcion_programa
        FOREIGN KEY (id_programa) REFERENCES programas(id_programa)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Tabla 5: historial_estatus
-- Registro de cada cambio de estatus por inscripcion
-- estatus_anterior = NULL en el primer registro ya que pues es inscripcion inicial
CREATE TABLE historial_estatus (
    id_historial INT AUTO_INCREMENT PRIMARY KEY,
    id_inscripcion INT NOT NULL,
    estatus_anterior ENUM('activo','baja_empresa','baja_programa','egresado','inscrito','reingreso','suspendido')
    NULL COMMENT 'NULL si es el primer registro del alumno',
    estatus_nuevo ENUM('activo','baja_empresa','baja_programa', 'egresado','inscrito','reingreso','suspendido') NOT NULL,
    fecha_cambio DATE NOT NULL,
    motivo VARCHAR(255) NULL COMMENT 'Razon del cambio de estatus',
    CONSTRAINT fk_historial_inscripcion
     FOREIGN KEY (id_inscripcion) REFERENCES inscripciones(id_inscripcion)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

SET FOREIGN_KEY_CHECKS = 1;

